static uint8_t xtime(uint8_t a)
{
    //cf la definition de XTIME_IRRED_RETENUE dans aes.h

    if(a & 0x80) // le bit tout a gauche de a est un 1 (0x80 = 0b10..0) 
    {
        return (a << 1) ^ XTIME_IRRED_RETENUE; 
    }
    else
    {
        return a << 1;
    }
}

static void mixColumns(state_t s)
{
    for(int i = 0; i < 16; i += 4)
    {
        uint8_t t0 = s[i];
        uint8_t t1 = s[i+1];
        uint8_t t2 = s[i+2];
        uint8_t t3 = s[i+3];
        /*
         On se sert de deux choses: 
         multiplier par deux revient a faire l'operation xtime (cf les td et tp)
         multiplier par trois revient a multiplier par 2 et faire + une fois
         On est dans GF(2^8) donc l'addition est un xor
         On a simplement ecrit a la main les relations linéaires données par la multiplication
         matricielle qui determine mixColumns
            {
                {0x02, 0x03, 0x01, 0x01}
                {0x01, 0x02, 0x03, 0x01}
                {0x01, 0x01, 0x02, 0x03}
                {0x03, 0x01, 0x01, 0x02}
            }
        */
        s[i] = xtime(t0)^(xtime(t1)^t1)^t2^t3;
        s[i+1] = t0^xtime(t1)^(xtime(t2)^t2)^t3;
        s[i+2] = t0^t1^xtime(t2)^(xtime(t3)^t3);
        s[i+3] = (xtime(t0)^t0)^t1^t2^xtime(t3);
    }
}

static void inv_mixColumns(state_t s)
{
    /*
        L'inverse de la matrice de mixColumns est :
        {
            {0x0e, 0x0b, 0x0D, 0x09}
            {0x09, 0x0e, 0x0B, 0x0D}
            {0x0D, 0x09, 0x0E, 0x0B}
            {0x0B, 0x0D, 0x09, 0x0E}
        }
        On prends le vectuer (a, b, c, d). Cette matrice * ce vecteur nous donne
        {
            a*0x0E + b*0x0b + c*0x0D + d*0x09
            a*0x09 + b*0x0E + c*0x0B + d*0x0d
            a*0x0D + b*0x09 + c*0x0E + d*0x0B
            a*0x0B + b*0x0d + c*0x09 + d*0x0E
        }
        Pour mixcolumns, les equations allaient encore (on avait au pire des multiplications par 3 donc xtime(xtime)) et une addition)
        Mainteant on peut aller jusqu'a une multiplication par 0xE donc 14
        On va donc s'inspirer du square_and_multiply:
        multiplication par 0x0E: t*14 = t*(8+4+2) = t*8 + t*4 + t*2 = t*2^3 + t*2^2 + t*2
        multiplication par 0x0D: t*13 = t*(8+4+1) = t*2^3 + t*2^2 + t
        multiplication par 0x0B: t*11 = t*(8+2+1) = t*2^3 + t*2 + t
        multiplication par 0x09: t*9 = t*(8+1) = t*2^3 + t

        honnetement pas très sur que ca soit la meilleure methode ...
    */
    
    for(int i = 0; i < 16; i += 4)
    {
        uint8_t t0 = s[i];
        uint8_t t1 = s[i+1];
        uint8_t t2 = s[i+2];
        uint8_t t3 = s[i+3];

        uint8_t t0_2 = xtime(t0);       // t0 * 2
        uint8_t t0_4 = xtime(t0_2);     // t0 * 4
        uint8_t t0_8 = xtime(t0_4);     // t0 * 8

        uint8_t t1_2 = xtime(t1);
        uint8_t t1_4 = xtime(t1_2);
        uint8_t t1_8 = xtime(t1_4);

        uint8_t t2_2 = xtime(t2);
        uint8_t t2_4 = xtime(t2_2);
        uint8_t t2_8 = xtime(t2_4);

        uint8_t t3_2 = xtime(t3);
        uint8_t t3_4 = xtime(t3_2);
        uint8_t t3_8 = xtime(t3_4);

        s[i] = (t0_8 ^ t0_4 ^ t0_2) ^ (t1_8 ^ t1_2 ^ t1) ^ (t2_8 ^ t2_4 ^ t2) ^ (t3_8 ^ t3);
        s[i+1] = (t0_8 ^ t0) ^ (t1_8 ^ t1_4 ^ t1_2) ^ (t2_8 ^ t2_2 ^ t2) ^ (t3_8 ^ t3_4 ^ t3);
        s[i+2] = (t0_8 ^ t0_4 ^ t0) ^ (t1_8 ^ t1) ^ (t2_8 ^ t2_4 ^ t2_2) ^ (t3_8 ^ t3_2 ^ t3);
        s[i+3] = (t0_8 ^ t0_2 ^ t0) ^ (t1_8 ^ t1_4 ^ t1) ^ (t2_8 ^ t2) ^ (t3_8 ^ t3_4 ^ t3_2);
    }
}

static void addRoundKey(state_t s, const uint32_t roundKey[4])
{
    for(int c = 0; c < 4; c++)
    {
        uint32_t w = roundKey[c];
        s[c*4] ^= (w >> 24) & 0xFF;
        s[c*4 + 1] ^= (w >> 16) & 0xFF;
        s[c*4 + 2] ^= (w >> 8) & 0xFF;
        s[c*4 + 3] ^= w & 0xFF;
    }
}

void encryptBlock(const uint8_t in[BLOCK_SIZE], uint8_t out[BLOCK_SIZE], const uint32_t w[], int nr)
{
    state_t s;
    memcpy(s, in, BLOCK_SIZE);

    addRoundKey(s,w);

    for(int round = 1; round < nr; round++)
    {
        subBytes(s);
        shiftRows(s);
        mixColumns(s);
        //w pointe vers le debut du tableau
        //w+4 pointe vers w[3]
        //w+r*4 pointe vers w[0+r*3]
        //ca permet de regarder le sous tableau w[i], w[i+1], w[i+2], w[i+3] sans recreer
        //plusieurs variables intermediaires
        //on a vu ce genre de truc en LLP...
        addRoundKey(s, w+round*4);
    }
    subBytes(s);
    shiftRows(s);
    addRoundKey(s, w+nr*4);

    memcpy(out, s, BLOCK_SIZE);
}

void decryptBlock(const uint8_t in[BLOCK_SIZE], uint8_t out[BLOCK_SIZE], const uint32_t w[], int nr)
{
    state_t s;
    memcpy(s, in, BLOCK_SIZE);
    int round = nr;
    addRoundKey(s, w+round*4);
    for(int round = nr-1; round >= 1; round--)
    {
        inv_shiftRows(s);
        inv_subBytes(s);
        addRoundKey(s, w+round*4);
        inv_mixColumns(s);
    }
    inv_shiftRows(s);
    inv_subBytes(s);
    addRoundKey(s, w);
    memcpy(out, s, BLOCK_SIZE);
}
