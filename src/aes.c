static void shiftRows(state_t s)
{
    /*
        Ligne 0 :   0    4    8   12
        Ligne 1 :   1    5    9   13
        Ligne 2 :   2    6   10   14
        Ligne 3 :   3    7   11   15

        Ligne 0 :   0    4    8   12        Ligne 0 : on ne fait rien
        Ligne 1 :   5    9    13   1        Ligne i : permutation circulaire de i crans vers la gauche
        Ligne 2 :   10    14   2   6
        Ligne 3 :   15    3   7   11        
    */

    uint8_t tmp1 = s[1];
    s[1] = s[5];
    s[5] = s[9];
    s[9] = s[13];
    s[13] = tmp1;

    uint8_t tmp2_1 = s[2];
    uint8_t tmp2_2 = s[6];
    s[2] = s[10];
    s[6] = s[14];
    s[10] = tmp2_1;
    s[14] = tmp2_2;
    
    uint8_t tmp3 = s[15];
    s[15] = s[11];
    s[11] = s[7];
    s[7] = s[3];
    s[3] = tmp3;
}

